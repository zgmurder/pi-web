import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJiti } from 'jiti';
import mock from './__fixtures__/data-source-mysql.cjs';
const jiti = createJiti(import.meta.url, { alias: { mysql2: fileURLToPath(new URL('./__fixtures__/data-source-mysql.cjs', import.meta.url)) } });
test('executor bounds rows/bytes, uses read-only transaction and safe parameters, masks failures and destroys connections', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pi-db-query-'));
  const prior = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = root;
  try {
    const { changeDataSource } = await jiti.import('./data-sources.ts');
    const { executeDataSourceQuery, testDataSourceConnection, queryDataSourceSql, inspectDataSource } = await jiti.import('./data-source-query.ts');
    const [source] = await changeDataSource('save', { name: 'Test', host: 'localhost', port: 3306, database: 'test', user: 'reader', password: 'secret', tls: true, notes: '', queries: [{ name: 'total', description: 'count', sql: 'SELECT COUNT(*) AS total FROM alarms WHERE ts >= :start AND ts < :end' }] });
    const range = { start: '2026-10-11T16:00:00Z', end: '2026-10-12T07:00:00Z' };
    const result = await executeDataSourceQuery(source.id, 'total', range);
    assert.deepEqual(result.rows, [{ total: '42' }]);
    assert.equal(result.truncated, false);
    assert.ok(mock.state.queries.includes('START TRANSACTION READ ONLY'));
    assert.equal(mock.state.queries.at(-1).params.start, '2026-10-12 00:00:00');
    assert.match(mock.state.queries.at(-1).sql, /LIMIT 201$/);
    assert.equal(mock.state.options.multipleStatements, false);
    assert.equal(mock.state.options.ssl.rejectUnauthorized, true);
    mock.state.rows = Array.from({ length: 201 }, () => ({ n: 1 }));
    assert.equal((await executeDataSourceQuery(source.id, 'total', range)).rows.length, 200);
    mock.state.rows = [{ value: 'x'.repeat(64001) }];
    const large = await executeDataSourceQuery(source.id, 'total', range);
    assert.equal(large.truncated, true); assert.equal(large.rows.length, 0);
    mock.state.fail = true;
    await assert.rejects(executeDataSourceQuery(source.id, 'total', range), e => !e.message.includes('secret'));
    assert.equal(mock.state.destroyed, 4);
    await assert.rejects(executeDataSourceQuery(source.id, 'total', range, AbortSignal.abort()));
    assert.equal(mock.state.destroyed, 4);
    mock.state.fail = false;
    mock.state.rows = [{ connection_ok: 1 }];
    const { listDataSources } = await jiti.import('./data-sources.ts');
    const before = listDataSources();
    const { createDataSourceExtension } = await jiti.import('./data-source-extension.ts');
    let registered;
    createDataSourceExtension().factory({ registerTool(tool) { registered = tool; } });
    const info = await registered.execute('test', {}, undefined, undefined, { sessionManager: { getBranch: () => [{ type: 'custom', customType: 'pi-web:data-source', data: { id: source.id } }] } });
    const metadata = JSON.parse(info.content[0].text);
    assert.equal(metadata.capabilities.templatesRequired, false);
    assert.equal(metadata.capabilities.readOnlySql, true);
    assert.match(metadata.nextStep, /action=schema/);
    await testDataSourceConnection({ host: 'new-host', port: 3306, database: 'test', user: 'reader', password: 'draft-secret', tls: true });
    assert.equal(mock.state.options.host, 'new-host');
    assert.equal(mock.state.options.password, 'draft-secret');
    await testDataSourceConnection({ ...source, host: 'edited-host', queries: 'unfinished JSON' });
    assert.equal(mock.state.options.host, 'edited-host');
    assert.equal(mock.state.options.password, 'secret');
    assert.deepEqual(listDataSources(), before);
    await assert.rejects(testDataSourceConnection({ ...source, port: 0 }));
    await queryDataSourceSql(source.id, 'SELECT COUNT(*) AS total FROM alarms');
    assert.match(mock.state.queries.at(-1).sql, /SELECT COUNT/);
    await queryDataSourceSql(source.id, 'SELECT COUNT(*) FROM alarms WHERE ts >= :start AND ts < :end', range);
    assert.equal(mock.state.queries.at(-1).params.start, '2026-10-12 00:00:00');
    for (const sql of ['DELETE FROM alarms', 'SELECT 1; DROP TABLE alarms', 'SELECT SLEEP(10)', 'SELECT * FROM alarms FOR UPDATE', 'SELECT 1 INTO OUTFILE \'x\'', 'SELECT /* hint */ 1']) await assert.rejects(queryDataSourceSql(source.id, sql));
    await assert.rejects(queryDataSourceSql(source.id, 'SELECT :start, :end'));
    await inspectDataSource(source.id, "table'quoted");
    assert.equal(mock.state.queries.at(-1).params.table, "table'quoted");
    assert.equal(mock.state.queries.at(-1).params.database, 'test');
    assert.ok(!mock.state.queries.at(-1).sql.includes("table'quoted"));
    mock.state.rows = Array.from({ length: 201 }, () => ({ TABLE_NAME: 'alarms' }));
    const schema = await inspectDataSource(source.id, undefined, 200);
    assert.equal(schema.nextOffset, 400);
    await assert.rejects(inspectDataSource(source.id, undefined, -1));
  } finally {
    if (prior === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = prior;
    await rm(root, { recursive: true, force: true });
  }
});
